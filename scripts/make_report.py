"""Builds reports/REPORT.md from experiments/runs/*.json only. Nothing in the tables is typed by hand."""
import subprocess
from pathlib import Path

from sentinel.registry.records import load_records

ROOT = Path(__file__).resolve().parents[1]
SUBSETS = ("FD001", "FD002", "FD003", "FD004")


def latest(records):
    out = {}
    for r in records:
        out[(r.subset, r.name)] = r
    return out


def f(x, nd=2):
    return "n/a" if x is None or x != x else f"{x:.{nd}f}"


def pm(m, nd=2):
    return f"{m['mean']:.{nd}f} ± {m['std']:.{nd}f}"


def overlaps(a, b):
    return a[0] <= b[1] and b[0] <= a[1]


def leaderboard(recs, subset):
    rows = [r for (s, _), r in recs.items() if s == subset and r.test_metrics and "rmse" in r.test_metrics]
    rows.sort(key=lambda r: r.test_metrics["rmse"]["mean"])
    if not rows:
        return []
    best_ci = rows[0].test_metrics["rmse_ci95_seed_mean_prediction"]
    out = [f"### {subset}", "",
           "| Model | CV cut RMSE | Test RMSE (5 seeds) | Test 95% CI | CI overlaps best | Test MAE | NASA score | Fit s | Latency ms | Size KB |", "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        t, ci = r.test_metrics, r.test_metrics["rmse_ci95_seed_mean_prediction"]
        out.append(f"| {r.name} | {f(r.cv_metrics['cut_rmse']['mean'])} | {pm(t['rmse'])} | {ci[0]:.1f}-{ci[1]:.1f} | {'yes' if overlaps(ci, best_ci) else 'no'} | {f(t['mae']['mean'])} | "
                   f"{t['score']['mean']:,.0f} | {f(r.train_seconds, 1)} | {f(r.latency_single_ms)} | {r.model_size_bytes / 1024:,.0f} |")
    return out + [""]


def build() -> str:
    recs = latest(load_records())
    try:
        commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    except OSError:
        commit = ""
    hw = next(iter(recs.values())).hardware
    L = ["# SENTINEL evaluation report (generated)", "",
         "Generated by `scripts/make_report.py` from `experiments/runs/*.json`. All data are simulated (C-MAPSS) or a small lab dataset (battery). "
         "Test numbers come from the official test sets, each configuration evaluated once; ablations were scored on development CV only. "
         "Differences between models whose test confidence intervals overlap are not established.", "",
         f"Code version: `{commit or 'unknown'}`. Hardware: {hw.get('processor', 'n/a')}, device {hw.get('device', 'n/a')}, Python {hw.get('python', 'n/a')}.", "",
         "## 1. Model leaderboards (official test sets)", ""]
    for s in SUBSETS:
        L += leaderboard(recs, s)
    L += ["Figure: `reports/test_predictions.png` (actual versus predicted RUL and error distribution for the default model on each test set); "
          "`reports/training_curves_FD001.png` (GRU/LSTM training curves).", "",
          "## 2. Ablations (development CV only)", "",
          "| Subset | Variant | CV cut RMSE | CV all-step RMSE | CV late-life RMSE |", "|---|---|---|---|---|"]
    for (s, n), r in sorted(recs.items()):
        if s in SUBSETS and not r.test_metrics:
            c = r.cv_metrics
            L.append(f"| {s} | {n} | {pm(c['cut_rmse'])} | {pm(c['all_rmse'])} | {pm(c['late_rmse'])} |")
    tr = recs.get(("transfer", "transfer_lightgbm_window50"))
    if tr:
        L += ["", "## 3. Generalisation across subsets (test RMSE, cycles)", "",
              "Trained on the row subset, evaluated once on the column subset's official test set; diagonal is in-subset. Single seed, no confidence intervals.", ""]
        for v in ("source_norm", "target_norm"):
            L += [f"**{v}**", "", "| source \\ target | " + " | ".join(SUBSETS) + " |", "|---|" + "---|" * len(SUBSETS)]
            for a in SUBSETS:
                L.append(f"| {a} | " + " | ".join((lambda x, d: f"**{x:.1f}**" if d else f"{x:.1f}")(tr.test_metrics[v][f"{a}->{b}"]["rmse"], a == b) for b in SUBSETS) + " |")
            L.append("")
    L += ["## 4. Failure warnings (default thresholds, persistence 3)", "",
          "| Subset | tau | OOF precision | OOF recall | engines with useful alert | median lead | test precision | test recall |", "|---|---|---|---|---|---|---|---|"]
    for s in ("FD001", "FD004"):
        r = recs.get((f"{s}-warning", "warning_lightgbm_window50"))
        if r:
            for tau in ("30", "15"):
                o, t = r.cv_metrics["default_oof"][tau], r.test_metrics["default"][tau]
                L.append(f"| {s} | {tau} | {f(o['precision'])} | {f(o['recall'])} | {f(o['useful_alert_frac'])} | {f(o['median_lead'], 1)} | {f(t['precision'])} | {f(t['recall'])} |")
    L += ["", "## 5. Prediction intervals (coverage of RUL capped at 125)", "",
          "| Subset | nominal | method | dev coverage | test coverage | test 95% CI | dev mean width |", "|---|---|---|---|---|---|---|"]
    for s in ("FD001", "FD004"):
        r = recs.get((f"{s}-uncertainty", "intervals_lightgbm_window50"))
        if r:
            for lvl in ("0.8", "0.9"):
                for m in ("quantile", "cqr", "conformal"):
                    d, t = r.cv_metrics[f"{lvl}|{m}"], r.test_metrics[f"{lvl}|{m}"]
                    L.append(f"| {s} | {float(lvl):.0%} | {m} | {f(d['coverage'])} | {f(t['coverage'])} | {t['coverage_ci95'][0]:.2f}-{t['coverage_ci95'][1]:.2f} | {d['mean_width']:.1f} |")
    L += ["", "## 6. Anomaly detection", "",
          "Synthetic faults only (injected into healthy-phase data of held-out assets); no accuracy is claimed on real anomalies. Event detection rate at magnitude 5 healthy standard deviations, "
          "statistical detector; `stuck` is the no-signal control.", "",
          "| Subset | clean false-positive rate | spike | step | ramp | stuck | noise burst |", "|---|---|---|---|---|---|---|"]
    for s in ("FD001", "FD004"):
        r = recs.get((f"{s}-anomaly", "anomaly_detectors"))
        if r:
            inj = r.cv_metrics["synthetic_injection"]
            L.append(f"| {s} | {f(r.cv_metrics['clean_fpr']['statistical'], 3)} | " + " | ".join(f(inj[f"statistical|{k}|5"]["event_detection_rate"]) for k in ("spike", "step", "ramp", "stuck", "noise_burst")) + " |")
    L += ["", "## 7. Explainability (mean |SHAP| top signals, out-of-fold)", ""]
    for s in ("FD001", "FD004"):
        r = recs.get((f"{s}-explain", "shap_lightgbm_window50"))
        if r:
            imp = r.cv_metrics["shap_importance"]
            L.append(f"- {s}: " + ", ".join(f"{k} ({v:.1f})" for k, v in sorted(imp.items(), key=lambda kv: -kv[1])[:6]))
    L += ["", "## 8. Second machine type: NASA Li-ion battery (demonstration, 4 cells, leave-one-cell-out, no test set)", "",
          "| Variant | Model | RMSE, cycles (mean ± std over cells) | late-life RMSE |", "|---|---|---|---|"]
    for (s, n), r in sorted(recs.items()):
        if s.startswith("battery"):
            L.append(f"| {s} | {n} | {pm(r.cv_metrics['rmse'], 1)} | {f(r.cv_metrics['late_rmse']['mean'], 1)} |")
    L += ["", "## 9. Reproducibility", "",
          "Splits: `experiments/splits/`. Run records (config, seeds, metrics, hardware, timings): `experiments/runs/`. Per-asset test predictions: `experiments/predictions/`. "
          "Commands are in the README. Detailed analysis, caveats and negative results: `docs/EXPERIMENTS.md`; limitations: `docs/LIMITATIONS.md`.", ""]
    return "\n".join(L)


def main() -> None:
    out = ROOT / "reports" / "REPORT.md"
    out.write_text(build(), encoding="utf-8")
    print(out)


if __name__ == "__main__":
    main()
